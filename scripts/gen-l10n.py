#!/usr/bin/env python3
"""Generate crates/district-l10n's catalogs and Rust from contracts/i18n/ and
the catalogs, or check that what is committed is what they produce.

    python3 scripts/gen-l10n.py            # write everything below
    python3 scripts/gen-l10n.py --check    # fail if any of it is stale (CI)

What it writes, under crates/district-l10n/:

  catalog/api_errors.toml   one entry per error code in
                            contracts/i18n/api-errors.json (two for a code
                            whose sentence lists items: with and without)
  catalog/wire.toml         one entry per labelled value in
                            contracts/i18n/wire-vocabulary.json, its server
                            placeholders, and the generic labels for a value
                            this build does not know
  src/generated/core.rs, api_errors.rs, wire.rs
                            the accessors, by `tools/l10n/l10n.py gen --backend
                            rust`, one module per catalog
  src/generated/api_error_table.rs, wire_table.rs
                            code and value to accessor
  src/generated/english.rs  the English of each core entry without
                            arguments, as a constant, for the core's public
                            constants
  tests/generated/accessors.rs
                            every accessor called in both languages and held
                            to its catalog's text (tests/accessors.rs includes
                            it, unformatted)

catalog/core.toml is written by hand. The two catalogs written here keep any
`fr`, `state` and the other translation fields an entry already has, as long as
its English has not changed: `l10n.py import` writes French into them like into
any other catalog, and a regeneration does not lose it.

The contracts themselves are vendored by scripts/sync-contracts.py and the tools
by `l10n.py vendor`; this script reads both and changes neither.

Python 3.11 or newer, standard library only.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CRATE = ROOT / "crates" / "district-l10n"
CATALOGS = CRATE / "catalog"
GENERATED = CRATE / "src" / "generated"
CONTRACTS = ROOT / "contracts" / "i18n"
TOOL = ROOT / "tools" / "l10n" / "l10n.py"

# Each catalog and the module its accessors are generated into, as lib.rs names it.
MODULES = (
    ("core", "strings"),
    ("api_errors", "api_error_strings"),
    ("wire", "wire_strings"),
)
GEN_OPTS = ("--opt", "locale_path=crate::Locale", "--opt", "int_fmt=crate::format::integer")

# The fields a regeneration carries over from an entry whose English is unchanged.
KEPT = ("fr", "state", "same_ok", "fr_variant", "waive", "max", "id")

HEADER = "// @generated by scripts/gen-l10n.py from {source}. Do not edit; run the script."


def load_tool():
    spec = importlib.util.spec_from_file_location("l10n", TOOL)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


L10N = load_tool()


def slug(text: str) -> str:
    """A key segment: lower case, runs of anything else as one underscore."""
    s = re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")
    return s if re.match(r"[a-z]", s) else f"v_{s}"


def snake(name: str) -> str:
    """`callStatus` -> `call_status`."""
    return re.sub(r"(?<!^)([A-Z])", r"_\1", name).lower()


def humanize(raw: str) -> str:
    """What the desktop apps show today for a value with no label of its own:
    hyphens and underscores as spaces, the first letter capitalized."""
    words = raw.strip().replace("-", " ").replace("_", " ")
    return words[:1].upper() + words[1:]


def rust_str(text: str) -> str:
    return '"' + L10N.escape_c_like(text, "rust") + '"'


# Catalogs from the contracts.


def entry(en, ctx, screen, tier, note, args=None) -> dict:
    fields = {"en": en, "ctx": ctx, "screen": screen, "tier": tier}
    if args:
        fields["args"] = args
    fields["note"] = note
    return fields


def api_error_key(code: str) -> str:
    # Some codes differ only by case (`forbidden`, `FORBIDDEN`); key segments are
    # lower case, so the upper-case ones get their own group.
    return f"api_error.{slug(code)}" if code == code.lower() else f"api_error_caps.{slug(code)}"


def api_error_entries(doc: dict) -> tuple[dict, list[tuple[str, str, str | None]]]:
    """The catalog's entries by key, and (code, key, key without the list) per code."""
    placeholder = doc["itemsPlaceholder"]
    entries: dict[str, dict] = {}
    table = []
    for code, sentence in doc["codes"].items():
        key = api_error_key(code)
        note = (
            f"Shown on any screen when the service refuses a request with the error code "
            f"`{code}`, in place of the service's own English."
        )
        without = None
        if "listField" in sentence:
            assert placeholder in sentence["en"], code
            entries[key] = entry(
                sentence["en"], "error", "api_error", "T2",
                note + " {items} is the list of what the refusal names (field names or region "
                "names), joined with commas.",
                {"items": "str"},
            )
            without = f"{key}_without_list"
            entries[without] = entry(
                sentence["enWithoutList"], "error", "api_error", "T2",
                note + " This form is used when the service named nothing to list.",
            )
        else:
            entries[key] = entry(sentence["en"], "error", "api_error", "T2", note)
        table.append((code, key, without))
    return entries, table


def wire_entries(doc: dict) -> tuple[dict, list, list, list, list]:
    """The catalog's entries by key; (category, value, key) per labelled value;
    (category, fallback key) per category with a fallback of its own; (region,
    long key) per region; and (placeholder value, key)."""
    entries: dict[str, dict] = {}
    labels = []
    fallbacks = []
    longs = []
    for name, category in doc["categories"].items():
        group = snake(name)
        for value in category["values"]:
            key = f"wire.{group}.{slug(value['value'])}"
            en = value["en"] if value["en"] is not None else humanize(value["value"])
            # A value can name a part of itself in braces (`http-{status}`): the
            # catalog writes a literal brace doubled.
            en = en.replace("{", "{{").replace("}", "}}")
            note = f"A label for the stored value `{value['value']}` of {name}. {category['description']}"
            if value["en"] is None:
                note += " The service has no label for it; the English is the value as the apps show it."
            entries[key] = entry(en, "label", f"wire {group}", "T3", note)
            labels.append((name, value["value"], key))
            if "enLong" in value:
                long_key = f"wire.{group}_long.{slug(value['value'])}"
                entries[long_key] = entry(
                    value["enLong"], "label", f"wire {group}", "T3",
                    f"The long name of the data region `{value['value']}`, naming its datacenter.",
                )
                longs.append((value["value"], long_key))
        if "fallback" in category:
            key = f"wire.{group}.fallback"
            entries[key] = entry(
                category["fallback"]["en"], "label", f"wire {group}", "T3",
                f"The label for a value of {name} this build does not know, or none.",
            )
            fallbacks.append((name, key))
    entries["wire.generic.other"] = entry(
        "Other", "label", "wire generic", "T3",
        "The label for a stored status, type or outcome this version of the app has no label "
        "for. Never the stored English itself.",
    )
    placeholders = []
    for placeholder in doc["placeholders"]:
        value = placeholder["value"]
        key = f"wire.placeholder.{slug(value)}"
        entries[key] = entry(
            value, "label", "wire placeholder", "T3",
            f"Text the service stores or sends in English in place of a real value, in "
            f"{'; '.join(placeholder['fields'])}. Shown where that value is shown.",
        )
        placeholders.append((stored(value), key))
        # A spelling the service wrote before, still in stored rows, reads as
        # the same placeholder.
        for alias in placeholder.get("aliases", []):
            placeholders.append((stored(alias), key))
    return entries, labels, fallbacks, longs, placeholders


EM_DASH = "\u2014"


def stored(text: str) -> str:
    """The text as the service stores it: the vendored copy writes the em dash
    as " - " (scripts/sync-contracts.py), which no stored row holds."""
    return text.replace(" - ", f" {EM_DASH} ")


def rust_stored(text: str) -> str:
    """A Rust literal for stored text, its em dash written as an escape."""
    return rust_str(text).replace(EM_DASH, "\\u{2014}")


def render_catalog(name: str, entries: dict, previous: Path) -> str:
    """The canonical text of a generated catalog, keeping the translation fields of
    every entry whose English is unchanged."""
    old = {}
    if previous.is_file():
        old = {e.key: e.fields for e in L10N.load_catalog(previous).entries.values()}
    data: dict = {"meta": {"catalog": name, "platform": "rust", "apple": False}}
    for key, fields in entries.items():
        fields = dict(fields)
        before = old.get(key)
        if before is not None and before.get("en") == fields["en"]:
            for field in KEPT:
                if field in before:
                    fields[field] = before[field]
        node = data
        *parents, last = key.split(".")
        for part in parents:
            node = node.setdefault(part, {})
        node[last] = fields
    cat = L10N.catalog_from_data(previous, data)
    return L10N.emit_catalog(cat)


# Rust tables.


def api_error_table(table) -> str:
    lines = [HEADER.format(source="contracts/i18n/api-errors.json"), ""]
    lines.append("use crate::Locale;")
    lines.append("use crate::api_error_strings as s;")
    lines.append("")
    lines.append("/// The sentence for `code`, with `items` where it lists them, or `None` for a")
    lines.append("/// code the contract does not have.")
    lines.append("pub(crate) fn sentence(locale: Locale, code: &str, items: Option<&str>) -> Option<String> {")
    lines.append("    Some(match code {")
    for code, key, without in table:
        name = key.replace(".", "_")
        if without is None:
            lines.append(f"        {rust_str(code)} => s::{name}(locale).to_owned(),")
        else:
            lines.append(f"        {rust_str(code)} => match items {{")
            lines.append(f"            Some(items) => s::{name}(locale, items),")
            lines.append(f"            None => s::{without.replace('.', '_')}(locale).to_owned(),")
            lines.append("        },")
    lines.append("        _ => return None,")
    lines.append("    })")
    lines.append("}")
    return "\n".join(lines) + "\n"


def variant(name: str) -> str:
    return name[:1].upper() + name[1:]


def wire_table(labels, fallbacks, longs, placeholders) -> str:
    lines = [HEADER.format(source="contracts/i18n/wire-vocabulary.json"), ""]
    lines.append("use crate::wire::WireCategory;")
    lines.append("use crate::wire_strings as s;")
    lines.append("use crate::Locale;")
    lines.append("")
    lines.append("/// The label of `value` (trimmed, in lower case) in `category`, or `None` for a")
    lines.append("/// value the vocabulary does not have.")
    lines.append("pub(crate) fn label(locale: Locale, category: WireCategory, value: &str) -> Option<&'static str> {")
    lines.append("    Some(match (category, value) {")
    for name, value, key in labels:
        lines.append(
            f"        (WireCategory::{variant(name)}, {rust_str(value.strip().lower())}) => "
            f"s::{key.replace('.', '_')}(locale),"
        )
    lines.append("        _ => return None,")
    lines.append("    })")
    lines.append("}")
    lines.append("")
    lines.append("/// The category's own label for a value it does not know, when it has one.")
    lines.append("pub(crate) fn fallback(locale: Locale, category: WireCategory) -> Option<&'static str> {")
    lines.append("    Some(match category {")
    for name, key in fallbacks:
        lines.append(f"        WireCategory::{variant(name)} => s::{key.replace('.', '_')}(locale),")
    lines.append("        _ => return None,")
    lines.append("    })")
    lines.append("}")
    lines.append("")
    lines.append("/// A region's long name, or `None` for a region the vocabulary does not have.")
    lines.append("pub(crate) fn region_long(locale: Locale, value: &str) -> Option<&'static str> {")
    lines.append("    Some(match value {")
    for value, key in longs:
        lines.append(f"        {rust_str(value.lower())} => s::{key.replace('.', '_')}(locale),")
    lines.append("        _ => return None,")
    lines.append("    })")
    lines.append("}")
    lines.append("")
    lines.append("/// The label of a placeholder the service stores or sends, exactly as it")
    lines.append("/// sends it, or `None` for any other text.")
    lines.append("pub(crate) fn placeholder(locale: Locale, value: &str) -> Option<&'static str> {")
    lines.append("    Some(match value {")
    for value, key in placeholders:
        lines.append(f"        {rust_stored(value)} => s::{key.replace('.', '_')}(locale),")
    lines.append("        _ => return None,")
    lines.append("    })")
    lines.append("}")
    return "\n".join(lines) + "\n"


def english_consts(cat) -> str:
    """The English of each core entry without arguments, as a constant."""
    lines = [HEADER.format(source="catalog/core.toml"), ""]
    for e in sorted(cat.entries.values(), key=lambda e: e.segs):
        if e.args or e.plural:
            continue
        name = L10N.rust_name(e).upper()
        lines.append(f"/// `{e.key}` in English.")
        lines.append(f"pub const {name}: &str = {rust_str(e.en)};")
    return "\n".join(lines) + "\n"


# The accessor test.


def integer(locale: str, n: int) -> str:
    """crate::format::integer: plain digits in English, grouped by no-break
    spaces in French."""
    digits = str(abs(n))
    if locale == "FrCa":
        digits = "".join(
            ("\u00a0" if i and (len(digits) - i) % 3 == 0 else "") + d for i, d in enumerate(digits)
        )
    return ("-" if n < 0 else "") + digits


def expected(entry, locale: str, lang: str, forms, values: dict) -> str:
    """What the accessor returns in `locale` for `values`, where `lang`'s plural
    rules choose among `forms`."""
    if isinstance(forms, dict):
        n = values[entry.selector()]
        category = L10N.plural_category(lang, n)
        text = forms.get(category, forms["other"])
    else:
        text = forms
    out = []
    for kind, part in L10N.parse_text(text)[0]:
        if kind == "lit":
            out.append(part)
        elif isinstance(values[part], int):
            out.append(integer(locale, values[part]))
        else:
            out.append(values[part])
    return "".join(out)


def call(module: str, entry, locale: str, values: dict) -> str:
    args = [f"Locale::{locale}"]
    for name, kind in entry.args.items():
        args.append(str(values[name]) if kind == "int" else rust_str(values[name]))
    return f"{module}::{L10N.rust_name(entry)}({', '.join(args)})"


def accessor_test(cats) -> str:
    lines = [HEADER.format(source="the catalogs in crates/district-l10n/catalog/"), ""]
    lines.append("use district_l10n::{Locale, api_error_strings, strings, wire_strings};")
    for name, module in MODULES:
        cat = cats[name]
        lines.append("")
        lines.append("#[test]")
        lines.append(f"fn every_{name}_accessor_says_what_its_catalog_says() {{")
        for e in sorted(cat.entries.values(), key=lambda e: e.segs):
            counts = [1, 7, 0, 1_000_000] if e.plural else [1_204]
            for n in counts:
                values = {
                    name: (n if kind == "int" else "{" + name + "}")
                    for name, kind in e.args.items()
                }
                en = expected(e, "En", "en", e.en, values)
                fr_lang, fr_forms = ("fr", e.fr) if e.fr is not None else ("en", e.en)
                fr = expected(e, "FrCa", fr_lang, fr_forms, values)
                for locale, text in (("En", en), ("FrCa", fr)):
                    lines.append(
                        f"    assert_eq!({call(module, e, locale, values)}, {rust_str(text)});"
                    )
        lines.append("}")
    lines.append("")
    lines.append("#[test]")
    lines.append("fn french_is_complete_only_when_every_entry_has_it() {")
    complete = all(e.fr is not None for cat in cats.values() for e in cat.entries.values())
    lines.append(f"    assert!({'' if complete else '!'}std::hint::black_box(district_l10n::FR_COMPLETE));")
    lines.append("}")
    return "\n".join(lines) + "\n"


# Driving it.


def gen_rust(catalog: Path, out: Path) -> str:
    """The accessors l10n.py generates for one catalog."""
    with tempfile.TemporaryDirectory() as tmp:
        target = Path(tmp) / out.name
        subprocess.run(
            [sys.executable, str(TOOL), "gen", "--backend", "rust", str(catalog), "--out", str(target), *GEN_OPTS],
            check=True, capture_output=True, text=True,
        )
        return target.read_text(encoding="utf-8")


def outputs() -> dict[Path, str]:
    errors_doc = json.loads((CONTRACTS / "api-errors.json").read_text(encoding="utf-8"))
    wire_doc = json.loads((CONTRACTS / "wire-vocabulary.json").read_text(encoding="utf-8"))
    errors, error_table = api_error_entries(errors_doc)
    wire, labels, fallbacks, longs, placeholders = wire_entries(wire_doc)

    files: dict[Path, str] = {}
    files[CATALOGS / "api_errors.toml"] = render_catalog("api_errors", errors, CATALOGS / "api_errors.toml")
    files[CATALOGS / "wire.toml"] = render_catalog("wire", wire, CATALOGS / "wire.toml")
    files[GENERATED / "api_error_table.rs"] = api_error_table(error_table)
    files[GENERATED / "wire_table.rs"] = wire_table(labels, fallbacks, longs, placeholders)

    with tempfile.TemporaryDirectory() as tmp:
        cats = {}
        for name, _ in MODULES:
            path = CATALOGS / f"{name}.toml"
            text = files.get(path)
            if text is None:
                text = path.read_text(encoding="utf-8")
            staged = Path(tmp) / f"{name}.toml"
            staged.write_text(text, encoding="utf-8")
            cats[name] = L10N.load_catalog(staged)
            files[GENERATED / f"{name}.rs"] = gen_rust(staged, GENERATED / f"{name}.rs")
        files[CRATE / "tests" / "generated" / "accessors.rs"] = accessor_test(cats)
        files[GENERATED / "english.rs"] = english_consts(cats["core"])
    return files


def check_catalogs() -> list[str]:
    """`l10n.py check` on each catalog and its generated module, as the brief for
    the generated code asks: a stale or non-canonical file fails it."""
    problems = []
    for name, _ in MODULES:
        done = subprocess.run(
            [sys.executable, str(TOOL), "check", str(CATALOGS / f"{name}.toml"),
             "--gen", f"rust:{GENERATED / f'{name}.rs'}", *GEN_OPTS],
            capture_output=True, text=True,
        )
        if done.returncode != 0:
            problems.append(f"l10n.py check {name}.toml:\n{done.stdout}{done.stderr}")
    return problems


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if anything committed is stale")
    args = parser.parse_args(argv[1:])
    try:
        files = outputs()
    except subprocess.CalledProcessError as exc:
        print(f"gen-l10n: {' '.join(exc.cmd[:4])} failed:\n{exc.stdout}{exc.stderr}", file=sys.stderr)
        return 1
    except L10N.L10nError as exc:
        print("gen-l10n: " + "\n".join(exc.lines), file=sys.stderr)
        return 1
    stale = [path for path, text in files.items()
             if not path.is_file() or path.read_bytes() != text.encode("utf-8")]
    if args.check:
        problems = [f"{path.relative_to(ROOT)} is stale; run python3 scripts/gen-l10n.py" for path in stale]
        problems += check_catalogs()
        for problem in problems:
            print(f"gen-l10n: {problem}", file=sys.stderr)
        if not problems:
            print(f"gen-l10n: {len(files)} generated files are current")
        return 1 if problems else 0
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(files[path].encode("utf-8"))
        print(f"wrote {path.relative_to(ROOT)}")
    if not stale:
        print("gen-l10n: everything is current")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
